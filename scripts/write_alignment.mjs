// Turns a fit result (outputs/alignment-<venue>.json) into app/alignmentData.ts.
// Usage: node scripts/write_alignment.mjs outputs/alignment-08.json
import fs from 'node:fs';

const fit = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const r = (v, d) => +v.toFixed(d);
const el = (e) =>
  '[' + e.map(([k, l, ke]) => `['${k}', ${r(l, 3)}${k === 'S' ? ', ' + r(ke, 9) : ''}]`).join(', ') + ']';
const file = 'app/alignmentData.ts';
const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
const names = {inner: 'turf', turf: 'turf', outer: 'outer', dirt: 'dirt'};
const courseLines = Object.entries(fit.courses).map(([k, c]) => `      ${names[k]}: ${el(c.elems)},
`).join('');
const poses = Object.entries(fit.courses).filter(([, c]) => c.pose);
const poseLines = poses.length
  ? `    poses: {
${poses.map(([k, c]) => `      ${names[k]}: {x: ${r(c.pose.x, 4)}, z: ${r(c.pose.z, 4)}, h: ${r(c.pose.h, 6)}},
`).join('')}    },
`
  : '';
const entry = `  '${fit.venue}': {
    scale: ${r(fit.scale, 6)},
    pose: {x: ${r(fit.pose.x, 4)}, z: ${r(fit.pose.z, 4)}, h: ${r(fit.pose.h, 6)}},
${poseLines}    courses: {
${courseLines}    },
  },
`;
// Keep the entries of other venues.
const others = [...existing.matchAll(/^ {2}'(\d\d)': \{[\s\S]*?^ {2}\},\n/gm)].filter((m) => m[1] !== fit.venue).map((m) => m[0]);
fs.writeFileSync(file, `// Generated by scripts/fit_alignment.mjs and scripts/write_alignment.mjs. Do not edit.
import type {VenueAlignment} from './alignment';

export const ALIGNMENTS: Record<string, VenueAlignment> = {
${[...others, entry].join('')}};
`);
console.log('wrote', file);
